"""One fail-closed delivery classifier used by CI, the updater and images."""
import fnmatch
import hashlib
import json
from pathlib import Path, PurePosixPath

IGNORED = {"README.md", "DOCS.md", "CHANGELOG.md", "icon.png", "logo.png"}
SCHEMA_WORDS = (b"CREATE TABLE", b"ALTER TABLE", b"DROP TABLE", b"PRAGMA USER_VERSION", b"MIGRAT")


def digest(data):
    return hashlib.sha256(data).hexdigest()


def safe_path(name):
    p = PurePosixPath(name)
    return bool(name) and not p.is_absolute() and ".." not in p.parts and "\\" not in name


def runtime_path(path, spec):
    if not safe_path(path):
        return False
    p = PurePosixPath(path)
    if any(part in {"__pycache__", ".git", "node_modules", "tests"} for part in p.parts):
        return False
    # Dependencies, executable startup wrappers and app declarations are never live.
    if p.name.startswith(("requirements", "package", "Dockerfile")) or p.suffix in {".sh", ".yaml", ".yml", ".toml", ".lock"}:
        return False
    return any((fnmatch.fnmatchcase(path, root) and ("/" in root or "/" not in path)) if "*" in root else
               path == root or path.startswith(root + "/") for root in spec["roots"])


def ignored(path):
    p = PurePosixPath(path)
    return (p.parts[0] in {"tests", "android-helper", ".delivery"} or p.name == ".delivery.Dockerfile" or
            p.name in IGNORED or p.name.startswith("requirements-dev") or
            "__pycache__" in p.parts or p.suffix == ".pyc")


def manifest(files, spec, shared, config):
    """Hash all build inputs, not just familiar dependency filenames.

    Schema-bearing Python modules are frozen as a whole. A newly introduced
    schema/migration token also changes compatibility and requires an image.
    App-specific protected modules cover indirect persistence entry points.
    """
    runtime, boundary = {}, {}
    for path, data in sorted(files.items()):
        if ignored(path):
            continue
        live = runtime_path(path, spec)
        if live:
            runtime[path] = digest(data)
        schema = path.endswith((".py", ".mjs", ".cjs", ".js")) and any(w in data.upper() for w in SCHEMA_WORDS)
        if not live or schema or path in spec.get("protected", []):
            if path == "config.yaml":
                effective = dict(config)
                effective.pop("version", None)
                effective.pop("image", None)  # Image reference is generated by the publisher.
                data = json.dumps(effective, sort_keys=True).encode()
            boundary[path] = digest(data)
    boundary["@delivery"] = digest(shared)
    boundary["@spec"] = digest(json.dumps(spec, sort_keys=True).encode())
    compatibility = digest(json.dumps(boundary, sort_keys=True).encode())
    return {"format": 1, "compatibility": compatibility, "runtime": runtime,
            "boundary": boundary, "spec": spec}


def files_under(root):
    root = Path(root)
    result = {}
    for path in root.rglob("*"):
        if path.is_symlink():
            raise ValueError("Symlinks are not supported in deployable source")
        if path.is_file() and not ignored(path.relative_to(root).as_posix()):
            result[path.relative_to(root).as_posix()] = path.read_bytes()
    return result
